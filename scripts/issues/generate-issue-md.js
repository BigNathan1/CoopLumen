'use strict';

/**
 * Regenerates issue.md from the same 500-item backlog it already contains,
 * expanding every item into a quality issue body (Summary / Context /
 * Acceptance Criteria / Definition of Done) collapsed behind a <details> so
 * the file stays scannable at a glance while still holding full context.
 *
 * Source of truth for the raw item list stays issue.md itself: this script
 * re-parses the current file, so checking a box `[x]` before re-running
 * preserves that item's done state.
 *
 * Usage: node scripts/issues/generate-issue-md.js
 */

const fs = require('fs');
const path = require('path');
const { parseBacklog } = require('./parse');
const { PHASE_CONTEXT, CATEGORY_CONTEXT } = require('./context');
const { backlogRef, renderAcceptanceCriteria } = require('./render');

const ISSUE_MD = path.join(__dirname, '..', '..', 'issue.md');

function renderItem(issue) {
  const box = issue.done ? 'x' : ' ';
  const labelLine = issue.labels.map((l) => `\`${l}\``).join(' ');
  const criteria = renderAcceptanceCriteria(issue)
    .slice(1) // drop the "implemented as described above" restatement; the heading already states it
    .map((b) => `  - ${b}`)
    .join('\n');
  const doneNote = issue.done
    ? '\n  - ✅ Already completed in earlier project history.'
    : '';

  return `- [${box}] #${String(issue.number).padStart(3, '0')} ${labelLine} — ${issue.title}
  <details><summary>Acceptance criteria</summary>

${criteria || '  - Implemented and verified as described above.'}${doneNote}
  </details>`;
}

function groupBy(items, keyFn) {
  const groups = new Map();
  for (const item of items) {
    const key = keyFn(item);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(item);
  }
  return groups;
}

function main() {
  const items = parseBacklog(ISSUE_MD);
  if (items.length !== 500) {
    console.warn(`Expected 500 backlog items, parsed ${items.length}. Check issue.md formatting.`);
  }

  const byPhase = groupBy(items, (i) => i.phase);
  const doneCount = items.filter((i) => i.done).length;

  const sections = [];
  let categoryCounter = 0;
  for (const [phase, phaseItems] of byPhase) {
    sections.push(`## ${phase}\n\n${PHASE_CONTEXT[phase] ?? ''}\n`);

    const byCategory = groupBy(phaseItems, (i) => i.category);
    for (const [category, catItems] of byCategory) {
      categoryCounter++;
      const numbers = catItems.map((i) => i.number);
      const min = String(Math.min(...numbers)).padStart(3, '0');
      const max = String(Math.max(...numbers)).padStart(3, '0');
      // Keep the "Category N:" prefix exactly as parse.js's CATEGORY_RE expects,
      // so re-running this generator against its own prior output still finds
      // the category for every item instead of silently losing it.
      sections.push(
        `### Category ${categoryCounter}: ${category} (${min}–${max})\n\n${CATEGORY_CONTEXT[category] ?? ''}\n`
      );
      sections.push(catItems.map(renderItem).join('\n\n'));
      sections.push('---');
    }
  }

  const header = `# CoopLumen — 500 Issues to Production

> **This file is local only and is not committed to GitHub.**
> Track progress by checking off boxes as issues are resolved.
> Issues are grouped by phase and category, numbered #001–#500.
> Generated by \`node scripts/issues/generate-issue-md.js\` from this same file — re-run it any time after
> checking/unchecking boxes or editing an item's title/labels to refresh the expanded bodies below.
> The first 100 items are also pushed as real GitHub issues via \`node scripts/issues/push-to-github.js\`;
> see \`scripts/issues/pushed.json\` for the mapping between backlog number and GitHub issue number.

**Progress: ${doneCount}/500 resolved.**

## Legend

- \`[ ]\` Open
- \`[x]\` Resolved
- Labels: \`infra\` \`db\` \`backend\` \`frontend\` \`stellar\` \`auth\` \`test\` \`e2e\` \`ci/cd\` \`security\` \`phase-2\` \`phase-3\` \`phase-4\` \`perf\` \`docs\` \`good-first-issue\`

---

`;

  fs.writeFileSync(ISSUE_MD, header + sections.join('\n\n') + '\n');
  console.log(`Wrote ${items.length} items (${doneCount} done) to ${ISSUE_MD}`);
}

main();
