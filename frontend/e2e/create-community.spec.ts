// frontend/e2e/create-community.spec.ts
import { test, expect } from '@playwright/test';

const MOCK_PUBLIC_KEY = 'GABCDEFGHIJKLMNOPQRSTUVWXYZ1234567890ABCDEFGHIJKLMNOPQ';

test.describe('Create Community Flow', () => {
  test.beforeEach(async ({ page }) => {
    // 1. Inject the mock Freighter wallet to bypass the browser extension requirement
    await page.addInitScript((publicKey) => {
      const mockFreighter = {
        isConnected: async () => true,
        getPublicKey: async () => publicKey,
        signTransaction: async (xdr: string) => xdr,
        signAuthEntry: async (entry: string) => entry,
      };
      
      (window as any).freighter = mockFreighter;
      (window as any).freighterApi = mockFreighter;
    }, MOCK_PUBLIC_KEY);

    // 2. Authenticate before attempting the creation flow
    await page.goto('/');
    const connectButton = page.getByRole('button', { name: /connect wallet/i });
    if (await connectButton.isVisible()) {
      await connectButton.click();
      // Wait for authentication to resolve (e.g., waiting for the disconnect button to appear)
      await expect(page.getByRole('button', { name: /disconnect/i })).toBeVisible();
    }
  });

  test('successfully fills form, submits, and renders success state', async ({ page }) => {
    // 1. Navigate to the creation page
    await page.goto('/communities/create');

    // 2. Verify the form is ready
    const heading = page.getByRole('heading', { name: /create community/i });
    await expect(heading).toBeVisible();

    // 3. Fill out the required form fields
    const uniqueCommunityName = `E2E Test Community ${Date.now()}`;
    await page.getByLabel(/community name/i).fill(uniqueCommunityName);
    await page.getByLabel(/description/i).fill('This community was generated by an automated Playwright test running against the Docker Compose stack.');

    // 4. Submit the form
    const submitButton = page.getByRole('button', { name: /create/i });
    await expect(submitButton).toBeEnabled();
    await submitButton.click();

    // 5. Verify the success state against the real backend
    await page.waitForURL(/\/communities\/.+/);
    const newCommunityHeading = page.getByRole('heading', { name: uniqueCommunityName });
    await expect(newCommunityHeading).toBeVisible({ timeout: 10000 });
  });
});